BEGIN;

CREATE TABLE IF NOT EXISTS categorias_materiales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    descripcion TEXT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_categorias_materiales_codigo UNIQUE (codigo),
    CONSTRAINT uq_categorias_materiales_nombre UNIQUE (nombre),
    CONSTRAINT ck_categorias_materiales_codigo_no_vacio CHECK (length(trim(codigo)) > 0),
    CONSTRAINT ck_categorias_materiales_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);

CREATE TABLE IF NOT EXISTS proveedores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    ruc VARCHAR(20),
    telefono VARCHAR(40),
    correo VARCHAR(254),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_proveedores_ruc UNIQUE (ruc),
    CONSTRAINT ck_proveedores_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_proveedores_nombre
    ON proveedores (nombre);

CREATE TABLE IF NOT EXISTS materiales (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    unidad VARCHAR(30) NOT NULL,
    categoria_id INTEGER NOT NULL
        REFERENCES categorias_materiales(id) ON DELETE RESTRICT,
    maestro_partida_id INTEGER
        REFERENCES maestro_partidas(id) ON DELETE RESTRICT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_materiales_codigo UNIQUE (codigo),
    CONSTRAINT uq_materiales_maestro_partida UNIQUE (maestro_partida_id),
    CONSTRAINT ck_materiales_codigo_no_vacio CHECK (length(trim(codigo)) > 0),
    CONSTRAINT ck_materiales_descripcion_no_vacia CHECK (length(trim(descripcion)) > 0),
    CONSTRAINT ck_materiales_unidad_no_vacia CHECK (length(trim(unidad)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_materiales_categoria_activo
    ON materiales (categoria_id, activo);

CREATE TABLE IF NOT EXISTS materiales_precios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id INTEGER NOT NULL
        REFERENCES materiales(id) ON DELETE RESTRICT,
    proveedor_id INTEGER NOT NULL
        REFERENCES proveedores(id) ON DELETE RESTRICT,
    costo_unitario NUMERIC(18, 4) NOT NULL,
    moneda VARCHAR(3) NOT NULL DEFAULT 'NIO',
    unidad_precio VARCHAR(30) NOT NULL,
    fecha_vigencia TIMESTAMPTZ NOT NULL,
    registrado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    observacion TEXT,
    CONSTRAINT ck_materiales_precios_costo_no_negativo CHECK (costo_unitario >= 0),
    CONSTRAINT ck_materiales_precios_moneda_iso CHECK (length(moneda) = 3),
    CONSTRAINT ck_materiales_precios_moneda_mayusculas CHECK (moneda = upper(moneda)),
    CONSTRAINT ck_materiales_precios_unidad_no_vacia CHECK (length(trim(unidad_precio)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_materiales_precios_material_proveedor_vigencia
    ON materiales_precios (material_id, proveedor_id, fecha_vigencia, registrado_en);

CREATE INDEX IF NOT EXISTS ix_materiales_precios_material_vigencia
    ON materiales_precios (material_id, fecha_vigencia);

CREATE OR REPLACE FUNCTION rechazar_mutacion_materiales_precios()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION
        'El historial de precios es inmutable; inserte una nueva cotizacion.';
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_trigger
        WHERE tgname = 'trg_materiales_precios_inmutables'
          AND tgrelid = 'materiales_precios'::regclass
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER trg_materiales_precios_inmutables
        BEFORE UPDATE OR DELETE ON materiales_precios
        FOR EACH ROW
        EXECUTE FUNCTION rechazar_mutacion_materiales_precios();
    END IF;
END;
$$;

COMMIT;
