CREATE TABLE IF NOT EXISTS apus_maestros (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    unidad VARCHAR(30) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'Activo',
    creado_por_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_apus_maestros_nombre_no_vacio CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_apus_maestros_unidad_no_vacia CHECK (length(trim(unidad)) > 0),
    CONSTRAINT ck_apus_maestros_estado CHECK (estado IN ('Activo', 'Inactivo'))
);

CREATE INDEX IF NOT EXISTS ix_apus_maestros_estado_nombre
    ON apus_maestros (estado, nombre);

CREATE TABLE IF NOT EXISTS versiones_apu (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apu_maestro_id INTEGER NOT NULL
        REFERENCES apus_maestros(id) ON DELETE RESTRICT,
    numero INTEGER NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    descripcion VARCHAR(1000) NOT NULL,
    unidad VARCHAR(30) NOT NULL,
    costo_unitario NUMERIC(18, 4) NOT NULL,
    detalle JSON NOT NULL DEFAULT '[]',
    motivo TEXT NOT NULL,
    creado_por_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_versiones_apu_maestro_numero UNIQUE (apu_maestro_id, numero),
    CONSTRAINT ck_versiones_apu_numero_positivo CHECK (numero > 0),
    CONSTRAINT ck_versiones_apu_costo_no_negativo CHECK (costo_unitario >= 0),
    CONSTRAINT ck_versiones_apu_unidad_no_vacia CHECK (length(trim(unidad)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_versiones_apu_maestro_creado
    ON versiones_apu (apu_maestro_id, creado_en);

CREATE TABLE IF NOT EXISTS usos_apu (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_apu_id INTEGER NOT NULL
        REFERENCES versiones_apu(id) ON DELETE RESTRICT,
    version_proyecto_id INTEGER NOT NULL
        REFERENCES versiones_proyecto(id) ON DELETE RESTRICT,
    partida_id INTEGER REFERENCES partidas(id) ON DELETE SET NULL,
    partida_codigo VARCHAR(50) NOT NULL,
    partida_descripcion VARCHAR(500) NOT NULL,
    capitulo_codigo VARCHAR(30) NOT NULL,
    proyecto_nombre VARCHAR(200) NOT NULL,
    version_proyecto_numero INTEGER NOT NULL,
    apu_nombre VARCHAR(200) NOT NULL,
    version_apu_numero INTEGER NOT NULL,
    snapshot JSON NOT NULL,
    motivo TEXT NOT NULL,
    creado_por_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_usos_apu_version_proyecto
    ON usos_apu (version_proyecto_id, creado_en);
CREATE INDEX IF NOT EXISTS ix_usos_apu_partida
    ON usos_apu (partida_id, creado_en);
CREATE INDEX IF NOT EXISTS ix_usos_apu_version_apu
    ON usos_apu (version_apu_id, creado_en);

CREATE OR REPLACE FUNCTION rechazar_mutacion_apu_inmutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_TABLE_NAME = 'usos_apu'
       AND TG_OP = 'UPDATE'
       AND OLD.partida_id IS NOT NULL
       AND NEW.partida_id IS NULL
       AND (to_jsonb(OLD) - 'partida_id') = (to_jsonb(NEW) - 'partida_id') THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION
        'Las versiones y usos APU son inmutables; cree una nueva revisión o un nuevo uso.';
END;
$$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_versiones_apu_inmutables'
          AND tgrelid = 'versiones_apu'::regclass
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER trg_versiones_apu_inmutables
        BEFORE UPDATE OR DELETE ON versiones_apu
        FOR EACH ROW
        EXECUTE FUNCTION rechazar_mutacion_apu_inmutable();
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgname = 'trg_usos_apu_inmutables'
          AND tgrelid = 'usos_apu'::regclass
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER trg_usos_apu_inmutables
        BEFORE UPDATE OR DELETE ON usos_apu
        FOR EACH ROW
        EXECUTE FUNCTION rechazar_mutacion_apu_inmutable();
    END IF;
END;
$$;
