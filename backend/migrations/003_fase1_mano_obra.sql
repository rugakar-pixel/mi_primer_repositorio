CREATE TABLE IF NOT EXISTS presupuestos_mo_versiones (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_proyecto_id INTEGER NOT NULL
        REFERENCES versiones_proyecto(id) ON DELETE RESTRICT,
    configuracion JSON NOT NULL,
    revision INTEGER NOT NULL DEFAULT 1,
    total_mo NUMERIC(18, 4) NOT NULL DEFAULT 0,
    algoritmo_version VARCHAR(40) NOT NULL DEFAULT 'mo-2026-v1',
    actualizado_por_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_presupuestos_mo_version_proyecto UNIQUE (version_proyecto_id),
    CONSTRAINT ck_presupuestos_mo_revision_positiva CHECK (revision > 0),
    CONSTRAINT ck_presupuestos_mo_total_no_negativo CHECK (total_mo >= 0)
);

CREATE INDEX IF NOT EXISTS ix_presupuestos_mo_actualizado
    ON presupuestos_mo_versiones (actualizado_en);

CREATE TABLE IF NOT EXISTS presupuestos_mo_lineas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    presupuesto_mo_id INTEGER NOT NULL
        REFERENCES presupuestos_mo_versiones(id) ON DELETE RESTRICT,
    orden INTEGER NOT NULL,
    id_origen VARCHAR(100) NOT NULL,
    item INTEGER NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    unidad_medida VARCHAR(30) NOT NULL,
    cantidad NUMERIC(18, 6) NOT NULL,
    rendimiento_base NUMERIC(18, 6) NOT NULL,
    cant_oficiales NUMERIC(18, 6) NOT NULL,
    cant_ayudantes NUMERIC(18, 6) NOT NULL,
    ratio_ayudantes NUMERIC(18, 6),
    CONSTRAINT uq_presupuestos_mo_lineas_orden UNIQUE (presupuesto_mo_id, orden),
    CONSTRAINT ck_presupuestos_mo_lineas_cantidad CHECK (cantidad >= 0),
    CONSTRAINT ck_presupuestos_mo_lineas_rendimiento CHECK (rendimiento_base >= 0),
    CONSTRAINT ck_presupuestos_mo_lineas_oficiales CHECK (cant_oficiales >= 0),
    CONSTRAINT ck_presupuestos_mo_lineas_ayudantes CHECK (cant_ayudantes >= 0),
    CONSTRAINT ck_presupuestos_mo_lineas_item CHECK (item > 0),
    CONSTRAINT ck_presupuestos_mo_lineas_descripcion CHECK (length(trim(descripcion)) > 0),
    CONSTRAINT ck_presupuestos_mo_lineas_unidad CHECK (length(trim(unidad_medida)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_presupuestos_mo_lineas_presupuesto
    ON presupuestos_mo_lineas (presupuesto_mo_id, orden);
