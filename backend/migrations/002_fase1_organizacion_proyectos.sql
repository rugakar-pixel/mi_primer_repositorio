CREATE TABLE IF NOT EXISTS empresas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    razon_social VARCHAR(250),
    identificacion_fiscal VARCHAR(40) UNIQUE,
    pais VARCHAR(2) NOT NULL DEFAULT 'NI',
    moneda_base VARCHAR(3) NOT NULL DEFAULT 'NIO',
    estado VARCHAR(30) NOT NULL DEFAULT 'Activa',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_empresas_nombre_no_vacio CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_empresas_pais_iso CHECK (length(pais) = 2 AND pais = upper(pais)),
    CONSTRAINT ck_empresas_moneda_base_iso
        CHECK (length(moneda_base) = 3 AND moneda_base = upper(moneda_base))
);

CREATE INDEX IF NOT EXISTS ix_empresas_estado ON empresas (estado);

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(200) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    correo_normalizado VARCHAR(254) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'Activo',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuarios_correo_normalizado UNIQUE (correo_normalizado),
    CONSTRAINT ck_usuarios_nombre_no_vacio CHECK (length(trim(nombre)) > 0),
    CONSTRAINT ck_usuarios_correo_no_vacio CHECK (length(trim(correo_normalizado)) > 0)
);

CREATE INDEX IF NOT EXISTS ix_usuarios_estado ON usuarios (estado);

CREATE TABLE IF NOT EXISTS membresias_empresa (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id INTEGER NOT NULL REFERENCES empresas(id) ON DELETE RESTRICT,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    rol VARCHAR(30) NOT NULL DEFAULT 'Editor',
    estado VARCHAR(30) NOT NULL DEFAULT 'Activa',
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_membresias_empresa_usuario UNIQUE (empresa_id, usuario_id),
    CONSTRAINT ck_membresias_empresa_rol
        CHECK (rol IN ('Administrador', 'Editor', 'Lector'))
);

CREATE INDEX IF NOT EXISTS ix_membresias_usuario_estado
    ON membresias_empresa (usuario_id, estado);

ALTER TABLE proyectos ADD COLUMN IF NOT EXISTS empresa_id INTEGER;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'proyectos'::regclass
          AND confrelid = 'empresas'::regclass
          AND contype = 'f'
    ) THEN
        ALTER TABLE proyectos
            ADD CONSTRAINT fk_proyectos_empresa_id
            FOREIGN KEY (empresa_id) REFERENCES empresas(id) ON DELETE RESTRICT;
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS ix_proyectos_empresa_id ON proyectos (empresa_id);

CREATE TABLE IF NOT EXISTS versiones_proyecto (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id INTEGER NOT NULL REFERENCES proyectos(id) ON DELETE RESTRICT,
    numero INTEGER NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'Borrador',
    motivo TEXT NOT NULL,
    version_anterior_id INTEGER REFERENCES versiones_proyecto(id) ON DELETE RESTRICT,
    creado_por_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_versiones_proyecto_numero UNIQUE (proyecto_id, numero),
    CONSTRAINT ck_versiones_proyecto_numero_positivo CHECK (numero > 0)
);

CREATE INDEX IF NOT EXISTS ix_versiones_proyecto_proyecto_creado
    ON versiones_proyecto (proyecto_id, creado_en);

CREATE TABLE IF NOT EXISTS auditoria_eventos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    actor_tipo VARCHAR(30) NOT NULL DEFAULT 'usuario',
    empresa_id INTEGER REFERENCES empresas(id) ON DELETE SET NULL,
    proyecto_id INTEGER REFERENCES proyectos(id) ON DELETE SET NULL,
    version_proyecto_id INTEGER REFERENCES versiones_proyecto(id) ON DELETE SET NULL,
    accion VARCHAR(60) NOT NULL,
    entidad_tipo VARCHAR(80) NOT NULL,
    entidad_id VARCHAR(80) NOT NULL,
    motivo TEXT,
    origen VARCHAR(80) NOT NULL DEFAULT 'api',
    correlacion_id VARCHAR(100),
    valores_anteriores JSON,
    valores_nuevos JSON,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_auditoria_entidad
    ON auditoria_eventos (entidad_tipo, entidad_id, creado_en);
CREATE INDEX IF NOT EXISTS ix_auditoria_proyecto_creado
    ON auditoria_eventos (proyecto_id, creado_en);
CREATE INDEX IF NOT EXISTS ix_auditoria_empresa_creado
    ON auditoria_eventos (empresa_id, creado_en);
